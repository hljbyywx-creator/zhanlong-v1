/* T09 乐器试听乐谱（60 秒；不是正片配乐）。时间全部写死在本文件，不读 cue 表。
   0–16 编钟完整云霄主题＋低弦长音 | 18–26 埙毒鳄动机＋大提琴 D2 | 28–34 磬四击
   36–44 琵琶杀局音型＋军鼓反拍 | 46–56 古筝云霄压抑形＋管钟一击 | 57–60 静音。
   注：bowed（小提琴组）采样最低 A3，写 G2/D3 会超出音域被丢音；这里低弦用 cello 落实际音高。
   注：36–44 是 8 秒窗口，♩=96 的 16 分音符每个 0.15625 秒，窗口内写满 52 个音；
       两处扫弦落在窗口前半／后半的强拍（36.00、39.97），对应第 1、5 小节的重音位置。 */
export function buildScore() {
  const ev = [];
  const n = (i, t, m, v, d, o = {}) => ev.push({ k: 'n', i, t, m, v, d, ...o });
  const p = (i, t, v, o = {}) => ev.push({ k: 'p', i, t, v, ...o });

  /* ---------- 0–16s 云霄主题完整形（编钟，♩=60，力度 .7） ---------- */
  [[0, 67, 1], [1, 69, 1], [2, 74, 1], [3, 76, 1], [4, 79, 2], [6, 81, 1],
   [7, 79, 1], [8, 76, 1], [9, 74, 1], [10, 76, 1], [11, 69, 1], [12, 67, 4]]
    .forEach(([t, m, d]) => n('bell', t, m, .7, d, { send: .35 }));
  /* 低弦长音：0–8s G2+D3，8–16s C3+G3，力度 .35 */
  [[0, 43], [0, 50], [8, 48], [8, 55]].forEach(([t, m]) => n('cello', t, m, .35, 8, { att: .8, rel: 1.2, pan: .2, send: .25 }));

  /* ---------- 18–26s 毒鳄动机（埙，力度 .6） ---------- */
  n('xun', 18, 65, .6, .5, { bend: [[0, 0], [.35, 0], [.5, -200]], att: .05, rel: .12, send: .35 });   // F4 音头后下滑到 D4
  n('xun', 18.5, 61, .6, 1, { att: .06, send: .35 });
  n('xun', 19.5, 60, .6, 1, { att: .06, send: .35 });
  n('xun', 20.5, 59, .6, 4, { att: .08, env: [[0, 1], [2, 1], [4, 0]], rel: .15, send: .4 });          // B3 最后 2 秒降到 0
  n('cello', 18, 38, .3, 8, { att: .8, rel: 1.2, pan: .2, send: .25 });                                  // D2 长音

  /* ---------- 28–34s 磬四击（力度 .6） ---------- */
  [[28, 55], [29.5, 55], [31, 53], [32.5, 50]].forEach(([t, m]) => p('qing', t, .6, { m, send: .45 }));

  /* ---------- 36–44s 杀局音型（琵琶＋军鼓） ---------- */
  const step = 60 / 96 / 4;                               // 16 分音符
  for (let k = 0; k < 52; k++) {
    const t = 36 + k * step;
    if (k === 0 || k === 25) n('pipa', t, 57, .55, undefined, { tech: 'sao', chord: [50, 57, 62, 69], pan: -.25, send: .2 });
    else n('pipa', t, k % 2 ? 62 : 57, .55, undefined, { pan: -.25, send: .2 });
  }
  for (let t = 36 + .625 / 2; t < 44; t += .625) p('snare', t, .25, { lp: 5200, pan: .18, send: .18, gain: .32 });

  /* ---------- 46–56s 云霄压抑形（古筝，♩=60）＋管钟一击 ---------- */
  n('zheng', 46, 67, .6, 1, { pan: -.28, send: .3 });
  n('zheng', 47, 69, .6, 1, { pan: -.28, send: .3 });
  n('zheng', 48, 74, .6, 1, { pan: -.28, send: .3 });
  n('zheng', 49, 76, .6, 5, { pan: -.28, send: .3 });     // 用古筝自身衰减，不加长音
  n('tube', 46, 55, .4, 9, { send: .4 });                 // G3；截到 9 秒，留出 57s 后的静音

  return {
    events: ev, duration: 60, wet: .55, kills: [{ t0: 57, t1: 60 }],
    sections: [
      { name: '云霄主题（编钟）', t0: 0, t1: 16 },
      { name: '毒鳄动机（埙）', t0: 18, t1: 26 },
      { name: '磬四击', t0: 28, t1: 34 },
      { name: '杀局音型（琵琶＋军鼓）', t0: 36, t1: 44 },
      { name: '云霄压抑形（古筝）＋管钟', t0: 46, t1: 56 },
      { name: '静音', t0: 57, t1: 60 }
    ],
    marks: []
  };
}
